/// Computes the discriminant of an order.
pub fn quat_order_discriminant<T: BigIntAlg, P: QuatConfig<T>>(order: &QuatLattice<T, P>) -> T {
    let p = P::p();

    // The reduced trace form matrix for the standard basis (1, i, j, k) is diag(2, 2, 2p, 2p).
    let gram = [
        [T::from_i32(2), T::zero(), T::zero(), T::zero()],
        [T::zero(), T::from_i32(2), T::zero(), T::zero()],
        [T::zero(), T::zero(), T::from_i32(2) * p.clone(), T::zero()],
        [T::zero(), T::zero(), T::zero(), T::from_i32(2) * p.clone()],
    ];

    // det(basis^T * gram * basis)
    let mut prod = [
        [T::zero(), T::zero(), T::zero(), T::zero()],
        [T::zero(), T::zero(), T::zero(), T::zero()],
        [T::zero(), T::zero(), T::zero(), T::zero()],
        [T::zero(), T::zero(), T::zero(), T::zero()],
    ];

    for i in 0..4 {
        for j in 0..4 {
            let mut sum = T::zero();
            for k in 0..4 {
                sum = sum + order.generators[i].coords[k].clone() * gram[k][j].clone();
            }
            prod[i][j] = sum;
        }
    }

    let mut final_prod = [
        [T::zero(), T::zero(), T::zero(), T::zero()],
        [T::zero(), T::zero(), T::zero(), T::zero()],
        [T::zero(), T::zero(), T::zero(), T::zero()],
        [T::zero(), T::zero(), T::zero(), T::zero()],
    ];

    for i in 0..4 {
        for j in 0..4 {
            let mut sum = T::zero();
            for k in 0..4 {
                sum = sum + prod[i][k].clone() * order.generators[j].coords[k].clone();
            }
            final_prod[i][j] = sum;
        }
    }

    let mut final_mat: [IntQuat<T, P>; 4] = [
        IntQuat::zero(),
        IntQuat::zero(),
        IntQuat::zero(),
        IntQuat::zero()
    ];
    for i in 0..4 {
        final_mat[i] = IntQuat::new(
            final_prod[i][0].clone(), final_prod[i][1].clone(), 
            final_prod[i][2].clone(), final_prod[i][3].clone()
        );
    }

    let det = crate::quaternion::matrix::MatrixUtils::mat_4x4_inv_with_det_as_denom(None, &final_mat);

    let denom_sq = order.denom.clone() * order.denom.clone();
    let denom_4 = denom_sq.clone() * denom_sq;
    let denom_8 = denom_4.clone() * denom_4.clone();

    let sqr = det / denom_8;
    sqr.sqrt()
}

/// Checks if an order is maximal (discriminant == p).
pub fn quat_order_is_maximal<T: BigIntAlg, P: QuatConfig<T>>(order: &QuatLattice<T, P>) -> u32 {
    let disc = quat_order_discriminant(order);
    disc.ct_eq(P::p())
}
